"""Builds FlightData.lua from two MIT-licensed addons' flight data.

  InFlight (LudiusMaximus): measured flight times in seconds, per faction,
    source node ID -> destination node ID. On WoW Forever InFlight uses its
    Classic Era table with the Forever table on top; this does the same.
  FlightCountdown (burk3): flown length in yards of each direct hop, from
    WoW Forever's own flight path tables.

Usage:  python .tools/build_flight_data.py
Bump the commit hashes below to pick up newer data.
"""

import re
import sys
import urllib.request
from pathlib import Path

INFLIGHT = ("LudiusMaximus/InFlight", "4b2b3baed78b13c129405330e5abbdc0c0d6b8fd", "Defaults.lua")
COUNTDOWN = ("burk3/FlightCountdown", "a6b61d7f64a005bae94efeb9328a1729afc4bed5", "RouteData.lua")
SPEED = 30.4  # FlightCountdown's yards per second without Frequent Flier

OUT = Path(__file__).resolve().parent.parent / "FlightData.lua"


def fetch(repo, sha, path):
    url = f"https://raw.githubusercontent.com/{repo}/{sha}/{path}"
    with urllib.request.urlopen(url) as r:
        return r.read().decode("utf-8")


def block(text, name):
    """The `local name = { ... }` table body, braces balanced."""
    start = text.index(f"local {name} = {{")
    i = text.index("{", start)
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return text[i:j + 1]
    raise ValueError(name)


def parse_times(body):
    """{faction: {src: {dst: seconds}}} from an InFlight era table."""
    out, faction, src, depth = {}, None, None, 0
    for line in body.splitlines():
        line = line.split("--")[0].strip()
        if not line:
            continue
        m = re.match(r'\["(Horde|Alliance)"\]\s*=\s*\{', line)
        if m:
            faction = out.setdefault(m.group(1), {})
            continue
        m = re.match(r'\[(\d+)\]\s*=\s*\{', line)
        if m:
            src = faction.setdefault(int(m.group(1)), {})
            continue
        m = re.match(r'\[(\d+)\]\s*=\s*(\d+)\s*,?', line)
        if m:
            src[int(m.group(1))] = int(m.group(2))
    return out


def merge(base, top):
    for faction, nodes in top.items():
        f = base.setdefault(faction, {})
        for src, dsts in nodes.items():
            f.setdefault(src, {}).update(dsts)
    return base


def main():
    defaults = fetch(*INFLIGHT)
    times = merge(parse_times(block(defaults, "global_classic")),
                  parse_times(block(defaults, "global_forever")))
    route = fetch(*COUNTDOWN)
    yards = {int(k): int(v) for k, v in re.findall(r"\[(\d+)\]\s*=\s*(\d+)", route)}
    build = re.search(r'routeDataBuild\s*=\s*"([^"]+)"', route).group(1)

    n_times = sum(len(d) for f in times.values() for d in f.values())
    if n_times < 500 or len(yards) < 200:
        sys.exit(f"suspiciously little data: {n_times} times, {len(yards)} hops")

    lines = [
        "-- Ziri's Toolkit: flight times from other addons, used until you have",
        "-- flown a route yourself. Generated by .tools/build_flight_data.py, do not",
        "-- edit by hand.",
        "--",
        f"-- times: measured flight times in seconds, from InFlight",
        f"--   (github.com/{INFLIGHT[0]} @ {INFLIGHT[1][:7]}), Classic Era table with",
        "--   its WoW Forever table on top. [faction][from node ID][to node ID].",
        f"-- yards: flown length of each direct hop, from FlightCountdown",
        f"--   (github.com/{COUNTDOWN[0]} @ {COUNTDOWN[1][:7]}), WoW Forever {build}.",
        "--   [from node ID * 10000 + to node ID].",
        "--",
        "-- InFlight: MIT License, Copyright (c) 2009-2024 TotalPackage,",
        "--   2022 Deranjata, 2025-2026 LudiusMaximus",
        "-- FlightCountdown: MIT License, Copyright (c) 2026 burk3",
        "--",
        "-- Permission is hereby granted, free of charge, to any person obtaining a copy",
        "-- of this software and associated documentation files (the \"Software\"), to deal",
        "-- in the Software without restriction, including without limitation the rights",
        "-- to use, copy, modify, merge, publish, distribute, sublicense, and/or sell",
        "-- copies of the Software, and to permit persons to whom the Software is",
        "-- furnished to do so, subject to the following conditions:",
        "--",
        "-- The above copyright notice and this permission notice shall be included in all",
        "-- copies or substantial portions of the Software.",
        "--",
        "-- THE SOFTWARE IS PROVIDED \"AS IS\", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR",
        "-- IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,",
        "-- FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE",
        "-- AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER",
        "-- LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,",
        "-- OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE",
        "-- SOFTWARE.",
        "",
        "local ADDON_NAME, root = ...",
        "",
        "root.FlightData = {",
        f"    speed = {SPEED},",
        "    times = {",
    ]
    for faction in sorted(times):
        lines.append(f'        ["{faction}"] = {{')
        for src in sorted(times[faction]):
            dsts = times[faction][src]
            if not dsts:
                continue
            pairs = ", ".join(f"[{d}]={s}" for d, s in sorted(dsts.items()))
            lines.append(f"            [{src}] = {{ {pairs} }},")
        lines.append("        },")
    lines.append("    },")
    lines.append("    yards = {")
    keys = sorted(yards)
    for i in range(0, len(keys), 6):
        lines.append("        " + " ".join(f"[{k}]={yards[k]}," for k in keys[i:i + 6]))
    lines.append("    },")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}: {n_times} times, {len(yards)} hops (build {build})")


if __name__ == "__main__":
    main()
